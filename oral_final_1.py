class ViTBlock(layers.Layer):
    def __init__(self, embed_dim, num_heads, ff_dim, patch_size=4, **kwargs):
        super().__init__(**kwargs)
        self.embed_dim = embed_dim
        self.num_heads = num_heads
        self.ff_dim = ff_dim
        self.patch_size = patch_size

        self.patch_embed = layers.Conv2D(
            self.embed_dim,
            kernel_size=self.patch_size,
            strides=self.patch_size,
            padding='same'
        )
        self.layernorm1 = layers.LayerNormalization(epsilon=1e-6)
        self.mha = layers.MultiHeadAttention(num_heads=self.num_heads, key_dim=self.embed_dim)
        self.layernorm2 = layers.LayerNormalization(epsilon=1e-6)
        self.ffn = tf.keras.Sequential([
            layers.Dense(self.ff_dim, activation='relu'),
            layers.Dense(self.embed_dim),
        ])

    def call(self, x):
        # x shape: [B, H, W, C]
        x = self.patch_embed(x)  # e.g. if patch_size=2, H->H/2, W->W/2
        B, Hp, Wp, C = tf.shape(x)[0], tf.shape(x)[1], tf.shape(x)[2], tf.shape(x)[3]

        x = tf.reshape(x, (B, Hp * Wp, C))  # Flatten patches
        x = self.layernorm1(x)

        attn_output = self.mha(x, x)  # Self-Attention
        x = x + attn_output           # Skip connection

        x = self.layernorm2(x)
        ffn_output = self.ffn(x)
        x = x + ffn_output            # Skip connection

        # Reshape back to 2D
        x = tf.reshape(x, (B, Hp, Wp, C))
        return x

