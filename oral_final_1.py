def create_cnn_vit_unet(
    input_shape=(IMAGE_SIZE, IMAGE_SIZE, CHANNELS),
    num_classes=5,
    vit_embed_dim=128,
    vit_num_heads=4,
    vit_ff_dim=256,
    vit_patch_size=2   # <-- changed default to 2
):
    inputs = layers.Input(shape=input_shape)

    # ENCODER
    x = layers.Conv2D(32, 3, activation='relu', padding='same')(inputs)
    x = layers.MaxPooling2D(2)(x)
    skip1 = x  # shape ~ [128, 128, 32]

    x = layers.Conv2D(64, 3, activation='relu', padding='same')(x)
    x = layers.MaxPooling2D(2)(x)
    skip2 = x  # shape ~ [64, 64, 64]

    x = layers.Conv2D(128, 3, activation='relu', padding='same')(x)
    x = layers.MaxPooling2D(2)(x)
    skip3 = x  # shape ~ [32, 32, 128]

    x = layers.Conv2D(256, 3, activation='relu', padding='same')(x)
    x = layers.MaxPooling2D(2)(x)
    skip4 = x  # shape ~ [16, 16, 256]

    # Bottleneck
    x = layers.Conv2D(512, 3, activation='relu', padding='same')(skip4)

    # ViT BLOCK (with patch_size=2 to avoid shape mismatch)
    x = ViTBlock(
        embed_dim=vit_embed_dim,
        num_heads=vit_num_heads,
        ff_dim=vit_ff_dim,
        patch_size=vit_patch_size
    )(x)

    # Optionally align channels again
    x = layers.Conv2D(512, 1, activation='relu', padding='same')(x)

    # DECODER
    # Up 1:  (16 -> 32)  then concat skip4 (16,16)? No - now x is 8,8 if patch_size=4,
    # but with patch_size=2, shape is (8,8). So let's see:
    # Actually with patch_size=2: 16->8 inside ViT, then we do a TransposeConv(2) => 8->16
    # That matches skip4 (16,16).

    x = layers.Conv2DTranspose(256, 2, strides=2, activation='relu', padding='same')(x)
    # now 8->16
    x = layers.Concatenate()([x, skip4])  # skip4 is (16,16,256)
    x = layers.Conv2D(256, 3, activation='relu', padding='same')(x)

    # Up 2:  (16 -> 32)
    x = layers.Conv2DTranspose(128, 2, strides=2, activation='relu', padding='same')(x)
    x = layers.Concatenate()([x, skip3])  # skip3 is (32,32,128)
    x = layers.Conv2D(128, 3, activation='relu', padding='same')(x)

    # Up 3:  (32 -> 64)
    x = layers.Conv2DTranspose(64, 2, strides=2, activation='relu', padding='same')(x)
    x = layers.Concatenate()([x, skip2])  # skip2 is (64,64,64)
    x = layers.Conv2D(64, 3, activation='relu', padding='same')(x)

    # Up 4:  (64 -> 128)
    x = layers.Conv2DTranspose(32, 2, strides=2, activation='relu', padding='same')(x)
    x = layers.Concatenate()([x, skip1])  # skip1 is (128,128,32)
    x = layers.Conv2D(32, 3, activation='relu', padding='same')(x)

    # OUTPUTS
    distance_map = layers.Conv2D(1, kernel_size=1, activation='sigmoid', name="distance_map")(x)
    seg_map = layers.Conv2D(num_classes, kernel_size=1, activation='softmax', name="cell_map")(x)

    model = models.Model(inputs=inputs, outputs=[distance_map, seg_map])
    return model

